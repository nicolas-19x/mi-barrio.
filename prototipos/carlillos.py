def grid(txt):
    rows = [r for r in txt.strip('\n').split('\n')]
    for i, r in enumerate(rows):
        assert len(r) == 32, (i, len(r), r)
    while len(rows) < 48:
        rows.append('.' * 32)
    assert len(rows) == 48, len(rows)
    return [list(r) for r in rows]


def outline(g):
    """Contorno exterior automático: todo pixel vacío que toca la silueta."""
    out = [r[:] for r in g]
    for y in range(48):
        for x in range(32):
            if g[y][x] != '.':
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < 32 and 0 <= ny < 48 and g[ny][nx] not in '.O':
                    out[y][x] = 'O'
                    break
    return out


def shift_cols(g, x0, x1, y0, y1, dy):
    """Mueve un bloque de columnas (una pierna) dy filas; deja vacío lo que queda."""
    out = [r[:] for r in g]
    for x in range(x0, x1 + 1):
        col = [g[y][x] for y in range(y0, y1 + 1)]
        for y in range(y0, y1 + 1):
            out[y][x] = '.'
        for i, c in enumerate(col):
            ny = y0 + i + dy
            if y0 <= ny <= y1 + max(dy, 0):
                out[ny][x] = c
    return out


def bob(g, dy):
    if dy == 0:
        return [r[:] for r in g]
    blank = ['.'] * 32
    return [blank[:] for _ in range(dy)] + [r[:] for r in g[:48 - dy]]


def front_frames(base):
    idle = base
    # paso A: se levanta la pierna derecha (más corta); paso B: la izquierda
    a = shift_cols(base, 17, 22, 35, 42, -2)
    b = shift_cols(base, 9, 14, 35, 42, -2)
    breathe = bob(base, 1)
    return [idle, bob(a, 0), breathe, bob(b, 0)]


def side_frames(base):
    step = [list(r) for r in SIDE_STEP.strip('\n').split('\n')]
    a = [r[:] for r in base]
    for i, r in enumerate(step):
        a[33 + i] = r[:]
    # brazo: hacia adelante en A, hacia atrás en B
    def arm(g, d):
        o = [r[:] for r in g]
        for y in range(25, 30):
            seg = g[y][13:19]
            for x in range(13, 19):
                o[y][x] = g[y][x] if g[y][x] in 'kKx' else 'K'
            for i, c in enumerate(seg):
                if 13 + i + d < 32:
                    o[y][13 + i + d] = c
        return o
    stepA = arm(a, 1)
    stepB = arm(a, -1)
    return [base, stepA, bob(base, 1), stepB]


def mirror(g):
    return [list(reversed(r)) for r in g]


def to_img(g, scale=1):
    im = Image.new('RGBA', (32, 48), (0, 0, 0, 0))
    px = im.load()
    for y in range(48):
        for x in range(32):
            c = PAL[g[y][x]]
            if c:
                px[x, y] = c + (255,)
    if scale != 1:
        im = im.resize((32 * scale, 48 * scale), Image.NEAREST)
    return im


def main(out):
    rows = [
        front_frames(grid(FRONT)),
        front_frames(grid(BACK)),
        [mirror(f) for f in side_frames(grid(SIDE))],
        side_frames(grid(SIDE)),
    ]
    sheet = Image.new('RGBA', (32 * 4, 48 * 4), (0, 0, 0, 0))
    for r, frames in enumerate(rows):
        for c, f in enumerate(frames):
            sheet.paste(to_img(outline(f)), (c * 32, r * 48))
    os.makedirs(out, exist_ok=True)
    sheet.save(os.path.join(out, 'carlillos_sheet.png'))
    sheet.resize((sheet.width * 4, sheet.height * 4), Image.NEAREST).save(os.path.join(out, 'carlillos_sheet_x4.png'))
    return sheet


if __name__ == '__main__':
    main(sys.argv[1])
